/* 西元年份採歷史編號：-1 是西元前 1 年，沒有 0。時間軸在內部才用連續年 A。 */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory(require('./data/sexagenary-cycle-records.js'));
  else root.SexagenaryCore = factory(root.SexagenaryRecords);
})(typeof globalThis === 'object' ? globalThis : this, function (records) {
  'use strict';
  const stems = [...'甲乙丙丁戊己庚辛壬癸'];
  const branches = [...'子丑寅卯辰巳午未申酉戌亥'];
  const animals = [...'鼠牛虎兔龍蛇馬羊猴雞狗豬'];
  const stemEn = 'Jia Yi Bing Ding Wu Ji Geng Xin Ren Gui'.split(' ');
  const branchEn = 'Zi Chou Yin Mao Chen Si Wu Wei Shen You Xu Hai'.split(' ');
  const animalEn = 'Rat Ox Tiger Rabbit Dragon Snake Horse Goat Monkey Rooster Dog Pig'.split(' ');
  const TAU = 2 * Math.PI;
  const first = -3000, last = 3000, initial = 1894;
  const mod = (n, m) => ((n % m) + m) % m;
  function integer(n) {
    if (!Number.isSafeInteger(n)) throw new RangeError('Expected an integer');
    return n;
  }
  function serial(year) {
    integer(year);
    if (year === 0) throw new RangeError('No civil year zero');
    return year < 0 ? year + 1 : year;
  }
  function civil(a) { return integer(a) <= 0 ? a - 1 : a; }
  function shift(year, count) { return civil(serial(year) + integer(count)); }
  function distance(from, to) { return serial(to) - serial(from); }
  function describe(year) {
    const a = serial(year);
    const k = mod(a - 1984, 60), s = k % 10, b = k % 12;
    return { year, k, s, b, name:stems[s] + branches[b], en:stemEn[s] + '-' + branchEn[b],
      animal:animals[b], animalEn:animalEn[b], roc:a >= 1912 ? a - 1911 : a - 1912,
      record:records.events.find(item => item.year === year) || null };
  }
  function readYear(era, n) {
    if (!Number.isSafeInteger(n) || n < 1 || n > 1912 - serial(first)) return null;
    let result;
    switch (era) {
      case 'ad': result = n; break;
      case 'bc': result = -n; break;
      case 'roc': result = civil(1911 + n); break;
      case 'before': result = civil(1912 - n); break;
      default: return null;
    }
    return result >= first && result <= last ? result : null;
  }
  // Find a tooth pairing on the actual 60-position index, with every position as evidence.
  function inspectPair(s, b) {
    if (!Number.isInteger(s) || s < 0 || s > 9 || !Number.isInteger(b) || b < 0 || b > 11) throw new RangeError('Invalid tooth');
    const matches = [];
    for (let k = 0; k < 60; k++) if (k % 10 === s && k % 12 === b) matches.push(k);
    return { s, b, matches, possible:matches.length === 1 };
  }
  function nextOccurrence(year, k) {
    if (!Number.isInteger(k) || k < 0 || k >= 60) throw new RangeError('Invalid position');
    return shift(year, mod(k - describe(year).k, 60) || 60);
  }
  function compare(from, to, guess) {
    const a = describe(from), b = describe(to), delta = distance(from, to);
    return { from, to, delta, gap:Math.abs(delta), correct:Number.isInteger(guess) && guess === Math.abs(delta),
      sameStem:a.s === b.s, sameBranch:a.b === b.b, samePair:a.k === b.k, start:a.k, end:b.k,
      crossBC:(from < 0) !== (to < 0), crossROC:(from < 1912) !== (to < 1912),
      twoEvents:!!(a.record && b.record && from !== to),
      sameReign:!!(a.record && b.record && from !== to && a.record.reign === b.record.reign) };
  }
  // Same module. The left tooth points into a gap on the right at the pitch point.
  // XY angles are counterclockwise. Both inscriptions advance under the fixed upper pointers.
  function angles(t) {
    return { stem:t * TAU / 10, branch:Math.PI / 12 - t * TAU / 12, dial:-t * TAU / 60 };
  }
  function labelAngle(n, i) {
    return n === 10 ? Math.PI / 2 - i * TAU / n : Math.PI / 2 - Math.PI / n + i * TAU / n;
  }
  // Clock gearing. The face is an epicycloid generated by half the mating pitch
  // radius; the matching flank below pitch is radial. All dimensions use module 1.
  function gearOutline(teeth, mateTeeth = teeth === 10 ? 12 : 10) {
    const pitch = teeth / 2, roller = mateTeeth / 4;
    const tip = pitch + 1, root = pitch - 1.25, fillet = .18;
    const half = (Math.PI / 4 - .026) / pitch;
    const tangent = Math.sqrt((root + fillet) ** 2 - fillet ** 2);
    const filletAngle = Math.atan2(fillet, tangent);
    const span = pitch + roller;
    const roll = roller / pitch * Math.acos((span ** 2 + roller ** 2 - tip ** 2) / (2 * span * roller));
    // One upper flank, traced from the root fillet to the outer corner of a flat land.
    const flank = [];
    function polar(radius, angle) { return [radius * Math.cos(angle), radius * Math.sin(angle)]; }
    for (let j = 0; j <= 5; j++) {
      const a = -Math.PI + filletAngle + (Math.PI / 2 - filletAngle) * j / 5;
      const x = tangent + fillet * Math.cos(a), y = fillet + fillet * Math.sin(a);
      flank.push(polar(Math.hypot(x,y), half + Math.atan2(y,x)));
    }
    for (let j = 0; j <= 12; j++) {
      const t = roll * j / 12;
      const x = span * Math.cos(t) - roller * Math.cos(span / roller * t);
      const y = span * Math.sin(t) - roller * Math.sin(span / roller * t);
      flank.push(polar(Math.hypot(x,y), half - Math.atan2(y,x)));
    }
    const tooth = [];
    const rootEnd = half + filletAngle;
    for (let j = 0; j < 4; j++) tooth.push(polar(root, -Math.PI / teeth + (Math.PI / teeth - rootEnd) * j / 4));
    for (const [x,y] of flank) tooth.push([x,-y]);
    for (let j = flank.length - 1; j >= 0; j--) tooth.push(flank[j]);
    for (let j = 1; j < 4; j++) tooth.push(polar(root, rootEnd + (Math.PI / teeth - rootEnd) * j / 4));
    const points = [];
    for (let i = 0; i < teeth; i++) {
      const a = i * TAU / teeth, c = Math.cos(a), s = Math.sin(a);
      for (const [x,y] of tooth) points.push([x*c-y*s, x*s+y*c]);
    }
    return points;
  }
  // Two equal cranks carry a parallel rod. The remote 10-tooth pinion meshes
  // with the 60-tooth rim, so one turn of the stem shaft advances the dial by 1/6 turn.
  const drive = { module:.112, pinionTeeth:10, ringTeeth:60, crank:.48,
    stemX:-5.5, stemY:-1.2, dialX:.65, dialY:6.48 };
  drive.pinionX = drive.dialX - drive.module * (drive.pinionTeeth + drive.ringTeeth) / 2;
  function drivePose(turns) {
    const a = angles(turns), crankAngle = a.stem + Math.PI / 5;
    return { pinion:a.stem, rim:Math.PI / drive.ringTeeth + a.dial,
      dx:drive.crank * Math.cos(crankAngle), dy:drive.crank * Math.sin(crankAngle) };
  }
  return { stems, branches, animals, stemEn, branchEn, animalEn, first, last, initial, TAU, mod,
    events:records.events, sources:records.sources, serial, civil, shift, distance, describe, readYear,
    inspectPair, nextOccurrence, compare, angles, labelAngle, gearOutline, drive, drivePose };
});

const assert = require('assert/strict');
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const C = require('../js/home-core.js');
const ROOT = path.resolve(__dirname, '..'), w = {};
new Function('window', fs.readFileSync(path.join(ROOT, 'js/catalog.js'), 'utf8'))(w);
const labs = w.LAB_CATALOG, now = Date.parse('2026-11-15T04:00:00Z');
const ids = result => result.items.map(x => x.lab.s);
const cold = C.recommend(labs, {}, {}, now);
assert.equal(cold.items.length, 4);
assert.equal(new Set(cold.items.map(x => x.lab.d)).size, 4);
assert.deepEqual(ids(cold), ids(C.recommend(labs, {}, {}, now)));
for (const x of cold.items) { const first = labs.find(p => p.d === x.lab.d); assert.equal(x.lab.b, first.b); assert.equal(x.lab.c, first.c); }
const rotation = new Set();
const catalogSubjects = new Set(labs.map(x => x.d));
for (let i = 0; i < catalogSubjects.size; i++) C.recommend(labs, {}, {}, now + i * 86400000).items.forEach(x => rotation.add(x.lab.d));
assert.deepEqual(rotation, catalogSubjects, '一輪推薦涵蓋目錄裡的每一科');
const hist = { 'newton-second': { v: 8, s: 900, o: 20, t: now }, projectile: { v: 6, s: 1200, o: 16, t: now - 86400000 } };
const done = C.doneCounts(labs, { 'projectile-1': {}, 'projectile-2': {}, 'newton-second-h1': {}, 'not-a-lab-1': {} });
assert.equal(done.projectile, 2); assert.equal(done['newton-second'], 1);
const personal = C.recommend(labs, hist, done, now, 'projectile');
assert.equal(personal.items.length, 4);
assert(personal.items.some(x => x.lab.d !== 'physics'));
assert(personal.items.some(x => x.reason.type === 'chapter'));
assert(personal.items.every(x => x.reason && !['projectile', 'newton-second'].includes(x.lab.s)));
const counts = k => Object.values(personal.items.reduce((a, x) => { a[x.lab[k]] = (a[x.lab[k]] || 0) + 1; return a; }, {}));
assert(Math.max(...counts('c')) <= 2); assert(Math.max(...counts('d')) <= 2);
assert.deepEqual(ids(personal), ids(C.recommend(labs, hist, done, now, 'projectile')));
const allDone = Object.fromEntries(labs.map(x => [x.s, x.n || 100]));
assert.equal(C.recommend(labs, {}, allDone, now).items.length, 0);
const sparse = Object.fromEntries(labs.slice(0, -8).map(x => [x.s, 1]));
assert(C.recommend(labs, {}, sparse, now).items.every(x => !sparse[x.lab.s]));
const huge = {}; for (let i = 0; i < 250; i++) huge['lab-' + i] = { v: 1, s: 2, o: 3, t: i };
assert.equal(Object.keys(C.trimHistory(huge)).length, 200); assert(!C.trimHistory(huge)['lab-0']);
assert.equal(C.day(Date.parse('2026-11-14T16:00:00Z')), '2026-11-15');
const D = require('../js/daily-core.js');
for (const ms of [Date.parse('2026-11-15T15:59:59Z'), Date.parse('2026-11-15T16:00:00Z'), now]) {
  assert.equal(C.dayNumber(ms), D.dayNumber(ms)); assert.equal(C.msToReset(ms), D.msToReset(ms));
}
assert.equal(C.dailyProgress({ d:C.dayNumber(now), n:4 },now),4);
assert.equal(C.dailyProgress({ d:C.dayNumber(now), n:4 },now+86400000),0);
assert.deepEqual(C.holdings({cu:5,ag:-3,au:2,used:{cu:3,au:5}}),D.holdings({cu:5,ag:-3,au:2,used:{cu:3,au:5}}).map(({id,left})=>({id,left})));
assert.equal(C.rankNumber({rank:12,at:now-8*86400000},now),0);
assert.equal(C.rankNumber({rank:12,at:now-7*86400000},now),12);
assert.equal(C.shortName('牛頓第二定律（力學車實驗）'),'牛頓第二定律');
assert.equal(C.shortName('Newton’s second law (force and motion)'),'Newton’s second law');
const projectileOnly=C.recommend(labs,{projectile:{v:3,s:1200,t:now}},{},now);
const binary=projectileOnly.items.find(x=>x.lab.s==='binary-search');
assert(!binary || binary.reason.type!=='cross','二分搜尋不能因為拋體運動被說成同主題');
const artificial = [{s:'projectile',d:'phy',c:'ch-p',b:'p',r:['binary-search'],rs:{'binary-search':.03}}, {s:'binary-search',d:'info',b:'i',c:'ch-b'}];
assert.notEqual(C.recommend(artificial,{projectile:{v:1,t:now}},{},now).items[0].reason.type,'cross');
const {checkFresh}=require('../tools/catalog-dates.cjs');
const two=[{s:'x',d:'info',l:'2026-11-15'},{s:'y',d:'info',l:'2026-11-15'}];
assert.throws(()=>checkFresh(two,'2026-11-15'),/30%.*\ninfo 2\/2：x, y/);
assert.equal(checkFresh([two[0]],'2026-11-15').info.counted.length,1,'小科每七日至少可加 1 站');
assert.equal(checkFresh([{s:'x',d:'info',l:'2026-11-15'}],'2026-11-15',{x:'2026-11-15'}).info.incremental.length,0);
assert.throws(()=>checkFresh(two,'2026-11-15',{x:'2026-11-14'}),/30%/,'日期不符不能冒充初建站批次');
const dates=Array.from({length:10},(_,i)=>({s:'lab-'+i,d:'info',l:i<3?'2026-11-15':'2026-11-08'}));
assert.equal(checkFresh(dates,'2026-11-15').info.incremental.length,3,'剛好30%可通過，七天前不算新');
assert.throws(()=>checkFresh(dates.map((x,i)=>i===3?{...x,l:'2026-11-15'}:x),'2026-11-15'),/info 4\/10/);
const guard = JSON.parse(fs.readFileSync(path.join(ROOT, 'tools/home-v2-invariants.json')));
for (const before of guard.catalog) { const { s, d, b, c } = labs.find(x => x.s === before.s) || {}; assert.deepEqual({ s, d, b, c }, before); }
if (labs.length === guard.count) assert.equal(crypto.createHash('sha256').update(fs.readFileSync(path.join(ROOT, 'js/chapter-map.js'))).digest('hex'), guard.chapterSHA256);
console.log('推薦、日期輪替、帳號任務合併、上限與搬遷不變量全部通過');
